"""Turn Blender renders into game sprite sheets at 1x, 2x and 4x zoom.

usage: python3 -I art/tools/pack_vehicle.py <render_dir> <out_dir> <name>

Writes <name>_<zoom>x.png (32bpp RGBA), <name>_<zoom>x_mask.png (8bpp,
company-colour palette indices) and <name>_sprites.pnml with one template per
zoom level holding the crop rectangles and offsets for the 8 directions.
"""
import os
import sys

import nml.palette
from PIL import Image

FRAME_4X = 192
CC_INDEX = 0xCA  # middle shade of the company-colour ramp; the 32bpp pixel sets brightness
PAD = 1


def palette_image():
    p = Image.new("P", (1, 1))
    p.putpalette(nml.palette.raw_palette_data[0][:768])
    return p


def to_8bpp(sheet, msheet, pal):
    """8bpp fallback for the 8bpp blitter: quantise to the game palette.

    Uses only static colours (1..0xC5 except company colours, no animated range),
    and puts company-colour shades back where the mask marks paint.
    """
    raw = nml.palette.raw_palette_data[0][:768]
    allowed = [i for i in range(1, 0xE3) if not 0xC6 <= i <= 0xCD]
    quant = Image.new("P", (1, 1))
    quant.putpalette(sum(([raw[3 * i], raw[3 * i + 1], raw[3 * i + 2]] for i in allowed), []) +
                     raw[3 * allowed[-1]:3 * allowed[-1] + 3] * (256 - len(allowed)))
    rgb = Image.new("RGB", sheet.size, (0, 0, 0))
    rgb.paste(sheet, mask=sheet.getchannel("A"))
    q = rgb.quantize(palette=quant, dither=Image.Dither.FLOYDSTEINBERG).load()
    a, m = sheet.getchannel("A").load(), msheet.load()
    out = Image.new("P", sheet.size, 0)
    out.putpalette(raw)
    o = out.load()
    for j in range(sheet.height):
        for i in range(sheet.width):
            if a[i, j] < 128:
                continue
            if m[i, j]:
                r, g, b, _ = sheet.getpixel((i, j))
                o[i, j] = 0xC6 + min(7, max(r, g, b) * 8 // 256)
            else:
                o[i, j] = allowed[min(q[i, j], len(allowed) - 1)]
    return out


def main(src, out, name):
    os.makedirs(out, exist_ok=True)
    pal = palette_image()
    templates = []
    for zoom in (4, 2, 1):
        frame = FRAME_4X * zoom // 4
        origin = frame // 2  # the camera is centred on the vehicle's ground origin
        cells = []
        for d in range(8):
            rgba = Image.open(os.path.join(src, f"rgba_{d}.png")).convert("RGBA")
            mask = Image.open(os.path.join(src, f"mask_{d}.png")).convert("RGBA")
            if zoom != 4:
                rgba = rgba.resize((frame, frame), Image.LANCZOS)
                mask = mask.resize((frame, frame), Image.NEAREST)
            box = rgba.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
            rgba, mask = rgba.crop(box), mask.crop(box)
            cells.append((rgba, mask, box[0] - origin, box[1] - origin))
        w = sum(c[0].width + PAD for c in cells) + PAD
        h = max(c[0].height for c in cells) + 2 * PAD
        sheet = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        msheet = Image.new("P", (w, h), 0)
        msheet.putpalette(pal.getpalette())
        x = PAD
        lines = []
        for rgba, mask, ox, oy in cells:
            sheet.paste(rgba, (x, PAD))
            m = Image.new("P", rgba.size, 0)
            mp, ap = mask.load(), rgba.getchannel("A").load()
            for j in range(rgba.height):
                for i in range(rgba.width):
                    if mp[i, j][0] > 127 and mp[i, j][3] > 127 and ap[i, j] > 8:
                        m.putpixel((i, j), CC_INDEX)
            msheet.paste(m, (x, PAD))
            lines.append(f"    [{x}, {PAD}, {rgba.width}, {rgba.height}, {ox}, {oy}]")
            x += rgba.width + PAD
        sheet.save(os.path.join(out, f"{name}_{zoom}x.png"))
        if zoom == 1:
            to_8bpp(sheet, msheet, pal).save(os.path.join(out, f"{name}_1x_8bpp.png"))
        msheet.save(os.path.join(out, f"{name}_{zoom}x_mask.png"))
        templates.append(f"template tmpl_{name}_{zoom}x() {{\n" + "\n".join(lines) + "\n}\n")
    with open(os.path.join(out, f"{name}_sprites.pnml"), "w") as f:
        f.write("// Generated by art/tools/pack_vehicle.py. Do not edit.\n" + "\n".join(templates))


if __name__ == "__main__":
    main(*sys.argv[1:4])
